def main():
    rows, seen = [], set()
    for cat, d in W.items():
        for diff, blob in d.items():
            for r in parse(cat, diff, blob):
                key = (r[0], r[1], r[2])
                if key in seen:
                    print('ซ้ำ:', key, file=sys.stderr); continue
                seen.add(key); rows.append(r)
    vals = []
    for cat, diff, ans, al in rows:
        arr = 'array[' + ','.join(q(a) for a in al) + ']::text[]' if al else "array[]::text[]"
        vals.append(f"({q(cat)},{q(diff)},{q(ans)},{arr})")
    sql = ["-- Draw & Guess v4: คลังคำเพิ่ม + alias + ลบคำซ้ำข้ามหมวด (สร้างจาก supabase/gen_words_v4.py ห้ามแก้มือ)",
           "-- รันหลัง draw_guess_words_v3.sql รันซ้ำได้",
           "insert into public.draw_guess_words(category,difficulty,answer,aliases) values"]
    sql.append(',\n'.join(vals))
    sql.append("on conflict (category,difficulty,answer) do nothing;")
    # คำที่ไปซ้ำกับ answer เดิมในหมวดอื่น: เก็บแถวเก่าสุดไว้แถวเดียว
    sql.append("delete from public.draw_guess_words w using public.draw_guess_words k\n"
               " where w.answer = k.answer and w.id <> k.id and (k.created_at, k.id::text) < (w.created_at, w.id::text);")
    for ans, al in ALIASES.items():
        arr = 'array[' + ','.join(q(a) for a in al) + ']::text[]'
        sql.append(f"update public.draw_guess_words set aliases = (select coalesce(array_agg(distinct x), '{{}}') from unnest(aliases || {arr}) x) where answer = {q(ans)};")
    out = pathlib.Path(__file__).parent / 'draw_guess_words_v4.sql'
    out.write_text('\n'.join(sql) + '\n', encoding='utf-8')
    by = {}
    for r in rows: by[r[0]] = by.get(r[0], 0) + 1
    print(len(rows), 'คำใหม่ (ก่อนตัดซ้ำกับของเดิม)', by)

if __name__ == '__main__':
    main()

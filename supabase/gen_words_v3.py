def q(s):
    return "'" + s.replace("'", "''") + "'"

def parse(cat, diff, blob):
    out = []
    for tok in blob.split(','):
        tok = tok.strip()
        if not tok: continue
        parts = tok.replace('=', '/').split('/')
        ans, aliases = parts[0].strip(), [a.strip() for a in parts[1:] if a.strip() and a.strip() != parts[0].strip()]
        out.append((cat, diff, ans, aliases))
    return out


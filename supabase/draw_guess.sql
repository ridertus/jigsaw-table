-- Draw & Guess MVP for Jigsaw Table
-- Run this file once in Supabase SQL Editor BEFORE deploying the updated lobby.html.
-- Guest identity note: player_id is supplied by the current LocalStorage-based client.
-- This prevents accidental rule violations but is NOT strong authentication against a malicious client.

create table if not exists public.draw_guess_words (
  id bigint generated by default as identity primary key,
  category text not null,
  difficulty text not null check (difficulty in ('easy', 'normal', 'hard')),
  answer text not null,
  aliases text[] not null default '{}',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  unique (category, difficulty, answer)
);

create table if not exists public.draw_guess_sessions (
  id uuid primary key default gen_random_uuid(),
  lobby_id text not null default 'main',
  status text not null check (status in ('drawing', 'reveal', 'ended')),
  controller_id text not null,
  settings jsonb not null default '{}'::jsonb,
  roster jsonb not null default '[]'::jsonb,
  round_no integer not null default 1 check (round_no > 0),
  drawer_id text not null,
  word_id bigint not null references public.draw_guess_words(id),
  category text not null,
  recent_word_ids bigint[] not null default '{}',
  started_at timestamptz not null default now(),
  ends_at timestamptz,
  revealed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists draw_guess_one_active_session_per_lobby
  on public.draw_guess_sessions (lobby_id)
  where status in ('drawing', 'reveal');

create index if not exists draw_guess_sessions_recent_idx
  on public.draw_guess_sessions (lobby_id, created_at desc);

create index if not exists draw_guess_words_pick_idx
  on public.draw_guess_words (category, difficulty) where enabled = true;

create table if not exists public.draw_guess_players (
  session_id uuid not null references public.draw_guess_sessions(id) on delete cascade,
  player_id text not null,
  display_name text not null,
  score integer not null default 0,
  join_order integer not null,
  solved_at timestamptz,
  created_at timestamptz not null default now(),
  primary key (session_id, player_id),
  unique (session_id, join_order)
);

create index if not exists draw_guess_players_order_idx
  on public.draw_guess_players (session_id, join_order);

create table if not exists public.draw_guess_strokes (
  id text primary key,
  session_id uuid not null references public.draw_guess_sessions(id) on delete cascade,
  round_no integer not null,
  drawer_id text not null,
  stroke jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists draw_guess_strokes_round_idx
  on public.draw_guess_strokes (session_id, round_no, created_at);

alter table public.draw_guess_words enable row level security;
alter table public.draw_guess_sessions enable row level security;
alter table public.draw_guess_players enable row level security;
alter table public.draw_guess_strokes enable row level security;

revoke all on public.draw_guess_words from anon, authenticated;
revoke all on public.draw_guess_sessions from anon, authenticated;
revoke all on public.draw_guess_players from anon, authenticated;
revoke all on public.draw_guess_strokes from anon, authenticated;

create or replace function public.dg_normalize_text(p_value text)
returns text
language sql
immutable
set search_path = ''
as $$
  select lower(regexp_replace(coalesce(p_value, ''), '[[:space:][:punct:]]+', '', 'g'));
$$;

revoke all on function public.dg_normalize_text(text) from public, anon, authenticated;

create or replace function public.dg_internal_state(p_session_id uuid, p_player_id text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_session public.draw_guess_sessions%rowtype;
  v_word public.draw_guess_words%rowtype;
  v_players jsonb;
  v_strokes jsonb;
  v_is_drawer boolean;
begin
  select * into v_session
  from public.draw_guess_sessions
  where id = p_session_id;

  if not found then
    return jsonb_build_object('active', false);
  end if;

  select * into v_word
  from public.draw_guess_words
  where id = v_session.word_id;

  v_is_drawer := coalesce(p_player_id, '') = v_session.drawer_id;

  select coalesce(jsonb_agg(jsonb_build_object(
    'player_id', p.player_id,
    'name', p.display_name,
    'score', p.score,
    'join_order', p.join_order,
    'solved', p.solved_at is not null,
    'solved_at', p.solved_at,
    'is_drawer', p.player_id = v_session.drawer_id
  ) order by p.join_order), '[]'::jsonb)
  into v_players
  from public.draw_guess_players p
  where p.session_id = v_session.id;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', s.id,
    'drawer_id', s.drawer_id,
    'stroke', s.stroke
  ) order by s.created_at, s.id), '[]'::jsonb)
  into v_strokes
  from public.draw_guess_strokes s
  where s.session_id = v_session.id and s.round_no = v_session.round_no;

  return jsonb_build_object(
    'active', v_session.status <> 'ended',
    'session_id', v_session.id,
    'status', v_session.status,
    'controller_id', v_session.controller_id,
    'settings', v_session.settings,
    'round_no', v_session.round_no,
    'drawer_id', v_session.drawer_id,
    'category', v_session.category,
    'started_at', v_session.started_at,
    'ends_at', v_session.ends_at,
    'revealed_at', v_session.revealed_at,
    'secret_word', case when v_is_drawer and v_session.status = 'drawing' then v_word.answer else null end,
    'answer', case when v_session.status in ('reveal','ended') then v_word.answer else null end,
    'is_participant', exists (
      select 1 from public.draw_guess_players p
      where p.session_id = v_session.id and p.player_id = p_player_id
    ),
    'players', v_players,
    'strokes', v_strokes
  );
end;
$$;

create or replace function public.dg_get_public_state(p_player_id text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session_id uuid;
begin
  if p_player_id is null or length(p_player_id) < 1 or length(p_player_id) > 80 then
    raise exception 'invalid player id';
  end if;

  select s.id into v_session_id
  from public.draw_guess_sessions s
  where s.lobby_id = 'main'
  order by s.created_at desc
  limit 1;

  if v_session_id is null then
    return jsonb_build_object('active', false);
  end if;

  return public.dg_internal_state(v_session_id, p_player_id);
end;
$$;

create or replace function public.dg_get_drawer_word(p_session_id uuid, p_player_id text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_answer text;
begin
  select w.answer into v_answer
  from public.draw_guess_sessions s
  join public.draw_guess_words w on w.id = s.word_id
  where s.id = p_session_id
    and s.status = 'drawing'
    and s.drawer_id = p_player_id;

  if v_answer is null then
    raise exception 'not the active drawer';
  end if;
  return v_answer;
end;
$$;

create or replace function public.dg_start_session(
  p_controller_id text,
  p_players jsonb,
  p_categories text[],
  p_difficulty text default 'normal',
  p_duration_seconds integer default 90
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session_id uuid;
  v_word public.draw_guess_words%rowtype;
  v_count integer;
  v_categories text[];
  v_roster jsonb;
  v_drawer_id text;
  v_duration integer;
begin
  if p_controller_id is null or length(p_controller_id) < 1 or length(p_controller_id) > 80 then
    raise exception 'invalid controller';
  end if;
  if p_players is null or jsonb_typeof(p_players) <> 'array' then
    raise exception 'invalid player list';
  end if;
  v_count := jsonb_array_length(p_players);
  if v_count < 2 or v_count > 4 then
    raise exception 'ต้องมีผู้เล่น 2–4 คน';
  end if;
  if not exists (
    select 1 from jsonb_array_elements(p_players) x
    where x->>'id' = p_controller_id
  ) then
    raise exception 'controller must be in the player list';
  end if;
  if exists (select 1 from jsonb_array_elements(p_players) x
    where coalesce(trim(x->>'id'),'') = '' or length(trim(x->>'id')) > 80) then
    raise exception 'invalid player id in roster';
  end if;
  if (select count(distinct x->>'id') from jsonb_array_elements(p_players) x) <> v_count then
    raise exception 'duplicate player id';
  end if;

  v_categories := array(select distinct c from unnest(coalesce(p_categories, '{}')) c
    where c = any(array['animals','food','objects','occupations','places','nature','vehicles','thai_culture','fantasy']::text[]));
  if coalesce(array_length(v_categories, 1), 0) = 0 then
    raise exception 'เลือกอย่างน้อยหนึ่งหมวดหมู่';
  end if;
  if p_difficulty is null or p_difficulty not in ('easy','normal','hard') then raise exception 'invalid difficulty'; end if;
  if coalesce(p_duration_seconds,90) not in (0,60,90,120) then raise exception 'invalid duration'; end if;
  v_duration := coalesce(p_duration_seconds, 90);

  if exists (select 1 from public.draw_guess_sessions s where s.lobby_id='main' and s.status in ('drawing','reveal')) then
    raise exception 'มีเกม Draw & Guess กำลังเล่นอยู่แล้ว';
  end if;

  select x->>'id' into v_drawer_id
  from jsonb_array_elements(p_players) with ordinality a(x, n)
  order by n limit 1;

  select * into v_word
  from public.draw_guess_words w
  where w.enabled and w.category = any(v_categories) and w.difficulty = p_difficulty
  order by random()
  limit 1;
  if not found then raise exception 'ไม่พบคำในหมวดหมู่และระดับนี้'; end if;

  v_roster := (
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', left(trim(x->>'id'),80),
      'name', left(coalesce(nullif(trim(x->>'name'),''),'ผู้เล่น'),32)
    ) order by n), '[]'::jsonb)
    from jsonb_array_elements(p_players) with ordinality a(x,n)
  );

  insert into public.draw_guess_sessions (
    lobby_id,status,controller_id,settings,roster,round_no,drawer_id,word_id,category,recent_word_ids,started_at,ends_at
  ) values (
    'main','drawing',p_controller_id,
    jsonb_build_object('categories',to_jsonb(v_categories),'difficulty',p_difficulty,'duration_seconds',v_duration),
    v_roster,1,v_drawer_id,v_word.id,v_word.category,array[v_word.id],now(),
    case when v_duration=0 then null else now()+make_interval(secs=>v_duration) end
  ) returning id into v_session_id;

  insert into public.draw_guess_players(session_id,player_id,display_name,join_order)
  select v_session_id, x->>'id', coalesce(nullif(x->>'name',''),'ผู้เล่น'), n::integer
  from jsonb_array_elements(v_roster) with ordinality a(x,n);

  return public.dg_internal_state(v_session_id,p_controller_id);
end;
$$;

create or replace function public.dg_submit_guess(
  p_session_id uuid,
  p_round_no integer,
  p_player_id text,
  p_guess text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session public.draw_guess_sessions%rowtype;
  v_word public.draw_guess_words%rowtype;
  v_player public.draw_guess_players%rowtype;
  v_normalized text;
  v_rank integer;
  v_delta integer;
  v_all_solved boolean;
  v_guessers integer;
  v_solved integer;
begin
  if p_guess is null or length(p_guess) > 80 then raise exception 'คำตอบยาวเกินไป'; end if;
  select * into v_session from public.draw_guess_sessions where id=p_session_id for update;
  if not found or v_session.status <> 'drawing' or v_session.round_no <> p_round_no then
    return jsonb_build_object('correct',false,'stale',true,'message','รอบนี้จบไปแล้ว');
  end if;
  if v_session.ends_at is not null and now() >= v_session.ends_at then
    update public.draw_guess_sessions set status='reveal',revealed_at=now(),updated_at=now() where id=v_session.id;
    return jsonb_build_object('correct',false,'expired',true,'message','หมดเวลาแล้ว');
  end if;
  if p_player_id = v_session.drawer_id then
    return jsonb_build_object('correct',false,'message','คนวาดไม่สามารถทายคำได้');
  end if;
  select * into v_player from public.draw_guess_players
  where session_id=p_session_id and player_id=p_player_id for update;
  if not found then return jsonb_build_object('correct',false,'message','คุณไม่ได้อยู่ในผู้เล่นรอบนี้'); end if;
  if v_player.solved_at is not null then return jsonb_build_object('correct',false,'already_solved',true,'message','คุณตอบถูกไปแล้ว'); end if;

  select * into v_word from public.draw_guess_words where id=v_session.word_id;
  v_normalized := public.dg_normalize_text(p_guess);
  if v_normalized = '' or not (
    v_normalized = public.dg_normalize_text(v_word.answer)
    or exists (select 1 from unnest(v_word.aliases) a where v_normalized=public.dg_normalize_text(a))
  ) then
    return jsonb_build_object('correct',false,'message','ยังไม่ถูก ลองอีกครั้ง');
  end if;

  select count(*)::integer into v_rank from public.draw_guess_players
  where session_id=p_session_id and player_id<>v_session.drawer_id and solved_at is not null;
  v_rank := v_rank + 1;
  v_delta := case when v_rank=1 then 3 else 1 end;

  update public.draw_guess_players set solved_at=now(),score=score+v_delta
  where session_id=p_session_id and player_id=p_player_id;
  update public.draw_guess_players set score=score+1
  where session_id=p_session_id and player_id=v_session.drawer_id;

  select count(*)::integer into v_guessers from public.draw_guess_players
  where session_id=p_session_id and player_id<>v_session.drawer_id;
  select count(*)::integer into v_solved from public.draw_guess_players
  where session_id=p_session_id and player_id<>v_session.drawer_id and solved_at is not null;
  v_all_solved := v_guessers > 0 and v_solved = v_guessers;

  if v_all_solved then
    update public.draw_guess_players set score=score+2
    where session_id=p_session_id and player_id=v_session.drawer_id;
    update public.draw_guess_sessions set status='reveal',revealed_at=now(),updated_at=now()
    where id=p_session_id and status='drawing';
  end if;

  return jsonb_build_object(
    'correct',true,'rank',v_rank,'score_delta',v_delta,
    'drawer_score_delta',1 + case when v_all_solved then 2 else 0 end,
    'round_finished',v_all_solved,
    'state',public.dg_internal_state(p_session_id,p_player_id)
  );
end;
$$;

create or replace function public.dg_finish_round(
  p_session_id uuid,
  p_round_no integer,
  p_requester_id text,
  p_reason text default 'timeout'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session public.draw_guess_sessions%rowtype;
  v_guessers integer;
  v_solved integer;
  v_finished_by_all boolean;
begin
  select * into v_session from public.draw_guess_sessions where id=p_session_id for update;
  if not found or v_session.round_no<>p_round_no then return jsonb_build_object('ok',false,'stale',true); end if;
  if v_session.status='reveal' then return jsonb_build_object('ok',true,'state',public.dg_internal_state(p_session_id,p_requester_id)); end if;
  if v_session.status<>'drawing' then return jsonb_build_object('ok',false,'stale',true); end if;
  if p_reason='skipped' and v_session.controller_id<>p_requester_id then raise exception 'เฉพาะผู้ควบคุมเกมเท่านั้นที่ข้ามรอบได้'; end if;
  if p_reason is null or p_reason not in ('timeout','skipped','all_solved') then raise exception 'invalid finish reason'; end if;
  if p_reason='timeout' and (v_session.ends_at is null or now()<v_session.ends_at) then
    return jsonb_build_object('ok',false,'not_expired',true);
  end if;

  select count(*)::integer into v_guessers from public.draw_guess_players where session_id=p_session_id and player_id<>v_session.drawer_id;
  select count(*)::integer into v_solved from public.draw_guess_players where session_id=p_session_id and player_id<>v_session.drawer_id and solved_at is not null;
  v_finished_by_all := v_guessers>0 and v_guessers=v_solved;
  if p_reason='all_solved' and not v_finished_by_all then return jsonb_build_object('ok',false,'not_all_solved',true); end if;
  if v_finished_by_all and p_reason<>'all_solved' then
    update public.draw_guess_players set score=score+2 where session_id=p_session_id and player_id=v_session.drawer_id;
  end if;

  update public.draw_guess_sessions set status='reveal',revealed_at=now(),updated_at=now() where id=p_session_id;
  return jsonb_build_object('ok',true,'state',public.dg_internal_state(p_session_id,p_requester_id));
end;
$$;

create or replace function public.dg_next_round(p_session_id uuid,p_controller_id text,p_round_no integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session public.draw_guess_sessions%rowtype;
  v_word public.draw_guess_words%rowtype;
  v_next_drawer text;
  v_next_order integer;
  v_duration integer;
  v_recent bigint[];
begin
  select * into v_session from public.draw_guess_sessions where id=p_session_id for update;
  if not found or v_session.status<>'reveal' or v_session.round_no<>p_round_no then raise exception 'รอบนี้ยังไม่พร้อมสำหรับรอบถัดไป'; end if;
  if v_session.controller_id<>p_controller_id then raise exception 'เฉพาะผู้ควบคุมเกมเท่านั้นที่เริ่มรอบถัดไปได้'; end if;

  select p.join_order into v_next_order from public.draw_guess_players p
  where p.session_id=p_session_id and p.player_id=v_session.drawer_id;
  select p.player_id into v_next_drawer from public.draw_guess_players p
  where p.session_id=p_session_id and p.join_order > coalesce(v_next_order,0)
  order by p.join_order limit 1;
  if v_next_drawer is null then
    select p.player_id into v_next_drawer from public.draw_guess_players p
    where p.session_id=p_session_id order by p.join_order limit 1;
  end if;

  v_recent := coalesce(v_session.recent_word_ids,'{}');
  if not (v_session.word_id = any(v_recent)) then v_recent := v_recent || v_session.word_id; end if;
  select * into v_word from public.draw_guess_words w
  where w.enabled
    and w.category = any(array(select jsonb_array_elements_text(v_session.settings->'categories')))
    and w.difficulty = v_session.settings->>'difficulty'
    and not (w.id=any(v_recent))
  order by random() limit 1;
  if not found then
    select * into v_word from public.draw_guess_words w
    where w.enabled
      and w.category = any(array(select jsonb_array_elements_text(v_session.settings->'categories')))
      and w.difficulty = v_session.settings->>'difficulty'
    order by random() limit 1;
  end if;
  if not found then raise exception 'ไม่พบคำสำหรับรอบถัดไป'; end if;

  v_duration := coalesce((v_session.settings->>'duration_seconds')::integer,90);
  update public.draw_guess_players set solved_at=null where session_id=p_session_id;
  update public.draw_guess_sessions set
    status='drawing',round_no=round_no+1,drawer_id=v_next_drawer,word_id=v_word.id,category=v_word.category,
    recent_word_ids=(v_recent[greatest(1,array_length(v_recent,1)-14):array_length(v_recent,1)]),
    started_at=now(),ends_at=case when v_duration=0 then null else now()+make_interval(secs=>v_duration) end,
    revealed_at=null,updated_at=now()
  where id=p_session_id;
  return public.dg_internal_state(p_session_id,p_controller_id);
end;
$$;

create or replace function public.dg_end_session(p_session_id uuid,p_controller_id text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session public.draw_guess_sessions%rowtype;
begin
  select * into v_session from public.draw_guess_sessions where id=p_session_id for update;
  if not found then return jsonb_build_object('ok',false); end if;
  if v_session.controller_id<>p_controller_id then raise exception 'เฉพาะผู้ควบคุมเกมเท่านั้นที่จบเกมได้'; end if;
  update public.draw_guess_sessions set status='ended',updated_at=now() where id=p_session_id;
  return jsonb_build_object('ok',true,'session_id',p_session_id,'state',public.dg_internal_state(p_session_id,p_controller_id));
end;
$$;

create or replace function public.dg_save_stroke(
  p_session_id uuid,
  p_round_no integer,
  p_drawer_id text,
  p_stroke jsonb
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session public.draw_guess_sessions%rowtype;
  v_points jsonb;
  v_id text;
  v_color text;
  v_width numeric;
begin
  select * into v_session from public.draw_guess_sessions where id=p_session_id for update;
  if not found or v_session.status<>'drawing' or v_session.round_no<>p_round_no or v_session.drawer_id<>p_drawer_id then
    raise exception 'ไม่มีสิทธิ์วาดในรอบนี้';
  end if;
  if v_session.ends_at is not null and now() >= v_session.ends_at then raise exception 'หมดเวลาแล้ว'; end if;
  v_id := p_stroke->>'id';
  v_color := p_stroke->>'color';
  v_points := p_stroke->'points';
  v_width := (p_stroke->>'width')::numeric;
  if v_id is null or length(v_id)>80 then raise exception 'invalid stroke id'; end if;
  if v_color is null or v_color !~ '^#[0-9a-fA-F]{6}$' then raise exception 'invalid stroke color'; end if;
  if v_width is null or v_width<0.001 or v_width>0.05 then raise exception 'invalid stroke width'; end if;
  if v_points is null or jsonb_typeof(v_points)<>'array' then
    raise exception 'invalid stroke points';
  end if;
  if jsonb_array_length(v_points)<4 or jsonb_array_length(v_points)>4000 or jsonb_array_length(v_points) % 2 <> 0 then
    raise exception 'invalid stroke points';
  end if;
  if exists (select 1 from jsonb_array_elements(v_points) as pt(value) where
    case when jsonb_typeof(pt.value)='number' then (pt.value::text)::numeric<0 or (pt.value::text)::numeric>1 else true end) then
    raise exception 'stroke coordinate outside canvas';
  end if;
  if (select count(*) from public.draw_guess_strokes where session_id=p_session_id and round_no=p_round_no)>=200 then
    raise exception 'ถึงขีดจำกัดจำนวนเส้นของรอบนี้แล้ว';
  end if;
  insert into public.draw_guess_strokes(id,session_id,round_no,drawer_id,stroke)
  values(v_id,p_session_id,p_round_no,p_drawer_id,p_stroke)
  on conflict (id) do nothing;
  return true;
end;
$$;

create or replace function public.dg_clear_canvas(p_session_id uuid,p_round_no integer,p_drawer_id text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare v_session public.draw_guess_sessions%rowtype;
begin
  select * into v_session from public.draw_guess_sessions where id=p_session_id for update;
  if not found or v_session.status<>'drawing' or v_session.round_no<>p_round_no or v_session.drawer_id<>p_drawer_id then
    raise exception 'ไม่มีสิทธิ์ล้างภาพในรอบนี้';
  end if;
  if v_session.ends_at is not null and now() >= v_session.ends_at then raise exception 'หมดเวลาแล้ว'; end if;
  delete from public.draw_guess_strokes where session_id=p_session_id and round_no=p_round_no;
  return true;
end;
$$;

